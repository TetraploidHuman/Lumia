#!/usr/bin/env bash
# Install `lumia` for NixOS:
#   ~/.local/lib/lumia/lumia      — full compiler (LLVM)
#   ~/.local/lib/lumia/lumia-lsp  — slim LSP (no LLVM; fast cold start)
#   ~/.local/bin/lumia           — wrapper with baked library paths
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=env.sh
source "$ROOT/scripts/env.sh"

PROFILE="${1:-release}"
case "$PROFILE" in
  release)
    CARGO_FLAGS=(--release)
    OUT_DIR=release
    ;;
  dev|debug)
    CARGO_FLAGS=()
    OUT_DIR=debug
    ;;
  *)
    echo "usage: $0 [release|debug]" >&2
    exit 1
    ;;
esac

echo "== build slim lumia-lsp (no codegen / LLVM) =="
# Isolate slim artifacts so the full rebuild below cannot overwrite them.
SLIM_TARGET="$ROOT/target/slim-lsp"
CARGO_TARGET_DIR="$SLIM_TARGET" cargo build -p lumia --no-default-features "${CARGO_FLAGS[@]}" --manifest-path "$ROOT/Cargo.toml"
LSP_SRC="$SLIM_TARGET/$OUT_DIR/lumia"
if [[ ! -x "$LSP_SRC" ]]; then
  echo "missing $LSP_SRC" >&2
  exit 1
fi

echo "== build full lumia (codegen) =="
cargo build -p lumia "${CARGO_FLAGS[@]}" --manifest-path "$ROOT/Cargo.toml"
BIN_SRC="$ROOT/target/$OUT_DIR/lumia"
if [[ ! -x "$BIN_SRC" ]]; then
  echo "missing $BIN_SRC" >&2
  exit 1
fi

LIBEXEC="${HOME}/.local/lib/lumia"
BIN_WRAP="${HOME}/.local/bin/lumia"
mkdir -p "$LIBEXEC" "$(dirname "$BIN_WRAP")"
cp -f "$BIN_SRC" "$LIBEXEC/lumia"
cp -f "$LSP_SRC" "$LIBEXEC/lumia-lsp"
chmod +x "$LIBEXEC/lumia" "$LIBEXEC/lumia-lsp"

# Resolve shared-lib dirs once at install time (avoid /nix/store globs on every launch).
_LIB_DIRS=()
_add_lib() {
  local p="$1"
  if [[ -d "$p" && "$p" != *"-static"* && "$p" != *static/lib ]]; then
    _LIB_DIRS+=("$p")
  fi
}
shopt -s nullglob
for p in \
  /nix/store/*-llvm-21.1.8-lib/lib \
  /nix/store/*-libffi-*/lib \
  /nix/store/*-zlib-*/lib \
  /nix/store/*-libxml2-*/lib \
  /nix/store/*-gcc-*-lib/lib; do
  _add_lib "$p"
done
LLVM_PREFIX=""
for p in /nix/store/*-llvm-21.1.8-dev; do
  if [[ -x "$p/bin/llvm-config" ]]; then
    LLVM_PREFIX="$p"
    break
  fi
done
shopt -u nullglob

JOINED=$(IFS=:; echo "${_LIB_DIRS[*]}")
LIBEXEC_ABS="$(cd "$LIBEXEC" && pwd)"

{
  echo '#!/usr/bin/env bash'
  echo '# Generated by scripts/install.sh — library paths baked at install time.'
  echo "export LD_LIBRARY_PATH=\"${JOINED}\${LD_LIBRARY_PATH:+:}\$LD_LIBRARY_PATH\""
  echo "export LIBRARY_PATH=\"${JOINED}\${LIBRARY_PATH:+:}\$LIBRARY_PATH\""
  if [[ -n "$LLVM_PREFIX" ]]; then
    echo "export LLVM_SYS_211_PREFIX=\"${LLVM_PREFIX}\""
  fi
  echo "LIBEXEC=\"${LIBEXEC_ABS}\""
  cat << 'WRAP'
if [[ "${1:-}" == "lsp" ]]; then
  exec "$LIBEXEC/lumia-lsp" "$@"
fi
exec "$LIBEXEC/lumia" "$@"
WRAP
} > "$BIN_WRAP"
chmod +x "$BIN_WRAP"

echo "installed: $BIN_WRAP"
echo "  compiler: $LIBEXEC/lumia ($(du -h "$LIBEXEC/lumia" | cut -f1))"
echo "  lsp:      $LIBEXEC/lumia-lsp ($(du -h "$LIBEXEC/lumia-lsp" | cut -f1))"
